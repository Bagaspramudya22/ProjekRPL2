    private void btnTambahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTambahActionPerformed
      String nama = txtTugas.getText().trim();
    if (nama.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Nama tugas tidak boleh kosong");
        return;
    }
    DefaultTableModel model = (DefaultTableModel) tblTugas.getModel();
    model.addRow(new Object[]{model.getRowCount() + 1, nama, "Belum selesai"});
    txtTugas.setText("");
    }//GEN-LAST:event_btnTambahActionPerformed

